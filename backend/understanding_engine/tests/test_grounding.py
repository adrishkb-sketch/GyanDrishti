"""Unit tests for Deterministic Grounding & Evidence Validation (Milestone 4.1)."""

import pytest
from understanding_engine.grounding import (
    DeterministicGroundingValidator,
    is_equation_supported,
    validate_numeric_claim,
)
from understanding_engine.schemas import (
    Concept,
    Equation,
    ImportantPoint,
    LectureUnderstanding,
)


def test_1_explicit_equation_in_transcript_accepted() -> None:
    """TEST 1: Transcript explicitly contains equation -> equation accepted."""
    transcript = "Here the circuit follows Ohm's law, where I = V / R as shown."
    eq = Equation(
        latex_or_text="I = V / R",
        description="Ohm's law",
        timestamp=10.0,
    )
    is_supp, status, snippet = is_equation_supported(eq, transcript)
    assert is_supp is True
    assert status == "supported"
    assert "Direct symbolic match" in snippet


def test_2_concept_described_without_equation_rejected() -> None:
    """TEST 2: Transcript describes concept but never states equation -> hallucinated equation rejected."""
    transcript = "According to Ohm's law, when resistance decreases, the electric current increases."
    eq = Equation(
        latex_or_text="I = V / R",
        description="Ohm's law",
        timestamp=15.0,
    )
    is_supp, status, _ = is_equation_supported(eq, transcript)
    assert is_supp is False
    assert status == "unsupported"

    # Test full understanding validation pipeline moves it to rejected_equations
    understanding = LectureUnderstanding(
        time_start=10.0,
        time_end=20.0,
        topic="Current and Resistance",
        equations=[eq],
    )
    validated = DeterministicGroundingValidator.validate_understanding(understanding, raw_transcript=transcript)
    assert len(validated.equations) == 0
    assert len(validated.rejected_equations) == 1
    assert validated.rejected_equations[0].grounding_status == "unsupported"


