def test_6_number_in_source_matches_extracted_accepted() -> None:
    """TEST 6: Number in source matches extracted number -> accepted."""
    transcript = "The AC frequency in this circuit is 50 Hz with an RMS voltage of 220 volts."
    point = ImportantPoint(
        point="The line frequency operates at 50 Hz.",
        timestamp_start=40.0,
        timestamp_end=45.0,
    )
    ok, unsupported = validate_numeric_claim(point.point, transcript)
    assert ok is True
    assert len(unsupported) == 0

    understanding = LectureUnderstanding(
        time_start=40.0,
        time_end=45.0,
        topic="AC Power",
        important_points=[point],
    )
    validated = DeterministicGroundingValidator.validate_understanding(understanding, raw_transcript=transcript)
    assert validated.important_points[0].importance == "high"
    assert "[Unverified" not in validated.important_points[0].point


def test_7_number_absent_from_source_flagged() -> None:
    """TEST 7: Number absent from source -> flagged/rejected."""
    transcript = "The line voltage is high and dangerous to touch."
    point = ImportantPoint(
        point="The line voltage is 440 volts.",
        timestamp_start=50.0,
        timestamp_end=55.0,
    )
    ok, unsupported = validate_numeric_claim(point.point, transcript)
    assert ok is False
    assert "440" in unsupported

    understanding = LectureUnderstanding(
        time_start=50.0,
        time_end=55.0,
        topic="Safety",
        important_points=[point],
    )
    validated = DeterministicGroundingValidator.validate_understanding(understanding, raw_transcript=transcript)
    assert validated.important_points[0].importance == "uncertain"
    assert "[Unverified number: 440]" in validated.important_points[0].point


def test_8_empty_transcript_no_unsupported_facts() -> None:
    """TEST 8: Empty transcript -> no unsupported facts accepted."""
    empty_transcript = ""
    understanding = LectureUnderstanding(
        time_start=0.0,
        time_end=10.0,
        topic="Some Hallucinated Topic",
        concepts=[Concept(name="Phantom Concept", explanation="Invented", timestamp_start=0.0, timestamp_end=5.0)],
        equations=[Equation(latex_or_text="I = V / R", description="Formula", timestamp=2.0)],
        important_points=[ImportantPoint(point="Fabricated point", timestamp_start=0.0, timestamp_end=5.0)],
    )
    validated = DeterministicGroundingValidator.validate_understanding(understanding, raw_transcript=empty_transcript)
    assert len(validated.equations) == 0
    assert len(validated.concepts) == 0
    assert len(validated.important_points) == 0
    assert len(validated.rejected_equations) == 1
    assert validated.grounding_score == 0.0
